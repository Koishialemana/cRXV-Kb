use std::{
    io::{self, Write},
    thread,
    time::Duration,
    process::Command,
};


const LOGO: &str = include_str!("../assets/logo.txt");

fn main() {

    print!("\x1b[2J\x1b[H");
    io::stdout().flush().unwrap();

    loop {
        println!("{LOGO}");
        print!("          Please enter the number of the action you wish to perform : ");
        io::stdout().flush().unwrap();
        let mut opcion: String = String::new();
        io::stdin()
            .read_line(&mut opcion)
            .expect("PANICO BRO");
        let opcion: u64 = match opcion.trim().parse() {
            Ok(num) => num,
            Err(_) => {
                panic!("01010000 01000001 01001110 01001001 01000011 01001111 00100000 01000010 01010010 01001111");
            }
        };

        match opcion {
            0 => {
                print!("\x1b[2J\x1b[H");
                io::stdout().flush().unwrap();
                break;
            },
            1 => {
                kb2es();
                break;
            },
            2 => {
                kb2uk();
                break;
            },
            3 => {
                kb2us();
                break;
            },
            4 => {
                kb2ge();
                break;
            },
            _ => {
                panic!("01010000 01000001 01001110 01001001 01000011 01001111 00100000 01000010 01010010 01001111");
            },
        };

    }
}

fn kb2es() {
    println!("          Please confirm if you wish to change your keyboard layout to Spanish");
    print!("          Y/N : ");
    io::stdout().flush().unwrap();

    let mut confirmar: String = String::new();
    io::stdin()
        .read_line(&mut confirmar)
        .expect("PANICO BRO");
    let confirmar = confirmar.trim().to_lowercase();

    let kb: String = String::from("es");

    match confirmar.as_str() {
        "y" => {
            println!("          Switch your distribution");
            animacion();
            swtkb(kb);
            println!("");
            println!("          Your distribution now is Spanish");
            thread::sleep(Duration::from_millis(2000));
            print!("\x1b[2J\x1b[H");
            io::stdout().flush().unwrap();
        },
        "n" => {
            println!("PANICO BRO");
        },
        _ => {
            println!("PANICO BRO");
        },
    }
}

