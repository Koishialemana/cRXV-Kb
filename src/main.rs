fn animacion() {
    let loading:String = String::from("Loading ");
    let frames = [".","..","..."];

    print!("\x1b[?25l");

    for recol in 0..30 {
        let frame = frames[recol % frames.len()];

        print!("\r\x1b[2K          {loading}{frame}");
        io::stdout().flush().unwrap();

        thread::sleep(Duration::from_millis(200));
    }

    print!("\x1b[?25h");
}

fn swtkb(mut kb: String) {
    let estado = Command::new("setxkbmap")
        .arg(&kb)
        .status()
        .expect("PANICO DE COMANDOS");
}
